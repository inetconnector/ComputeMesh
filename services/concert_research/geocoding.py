def normalize_city_name(city: str) -> str:
    """Normalizes a city string into a clean key for coordinate dictionary lookup."""
    text = (city or "").strip().lower()
    # Strip common administrative affixes and parentheses
    text = re.sub(r"\s*\(.*?\)", "", text)
    text = re.sub(
        r",\s*(deutschland|germany|bayern|baden-württemberg|hessen|nrw|nordrhein-westfalen|sachsen|thüringen|brandenburg|niedersachsen|schleswig-holstein|österreich|austria|schweiz|switzerland)$",
        "",
        text,
        flags=re.IGNORECASE,
    )
    text = text.strip()

    for src, dst in (("ä", "ae"), ("ö", "oe"), ("ü", "ue"), ("ß", "ss")):
        text = text.replace(src, dst)

    cleaned = " ".join("".join(ch if ch.isalnum() else " " for ch in text).split())
    return cleaned.replace(" ", "-")


def geocode_city(
    city: str,
    *,
    fetch_remote: bool = False,
    timeout_seconds: float = 2.5,
) -> tuple[float, float] | tuple[None, None]:
    """Resolves coordinates (latitude, longitude) for a city name.

    1. Checks offline high-accuracy table for exact match and normalized match.
    2. Checks common prefixes/substrings for multi-word city variations.
    3. Optionally falls back to open geocoding endpoint if enabled and available.
    """
    if not city or not city.strip():
        return (None, None)

    norm_key = normalize_city_name(city)
    if norm_key in KNOWN_CITY_COORDINATES:
        return KNOWN_CITY_COORDINATES[norm_key]

    raw_key = city.strip().lower()
    if raw_key in KNOWN_CITY_COORDINATES:
        return KNOWN_CITY_COORDINATES[raw_key]

    # Prefix / Substring matching for known multi-word cities (e.g. "Würzburg am Main")
    for k, coords in KNOWN_CITY_COORDINATES.items():
        if norm_key.startswith(k) or k.startswith(norm_key):
            return coords

    if not fetch_remote:
        return (None, None)

    # Optional remote OSM Nominatim fallback
    try:
        encoded = parse.quote(city.strip())
        url = f"https://nominatim.openstreetmap.org/search?q={encoded}&format=json&limit=1"
        req = request.Request(url, headers={"User-Agent": "ComputeMesh-ConcertResearch/1.0"})
        with request.urlopen(req, timeout=timeout_seconds) as resp:
            if resp.status == 200:
                data = json.loads(resp.read().decode("utf-8"))
                if data and isinstance(data, list) and len(data) > 0:
                    lat = float(data[0]["lat"])
                    lon = float(data[0]["lon"])
                    return (lat, lon)
    except Exception as exc:
        logger.debug("Remote geocoding failed for %r: %s", city, exc)

    return (None, None)
